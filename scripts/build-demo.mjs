// Builds demo/portfolio-demo.html: a single self-contained file that runs the
// whole app in the browser with simulated data. You can open it with a
// double-click, with no server and nothing to install.
//
//   npm run build:demo
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const OUT = path.join(root, 'demo', 'portfolio-demo.html');

export function buildDemo() {
  const css =
    read('public/styles.css') +
    `
.demo-bar { display: flex; flex-wrap: wrap; gap: 8px 12px; align-items: center; background: var(--surface-2); border: 1px solid var(--border); border-radius: 12px; padding: 10px 14px; margin-bottom: 16px; }
.demo-bar p { margin: 0; flex: 1 1 260px; min-width: 0; color: var(--muted); font-size: 13px; }
.demo-bar p b { color: var(--text); }
.demo-bar .btns { display: flex; gap: 6px; flex-wrap: wrap; }
`;

  const html = read('public/index.html');
  const head = html.split('<head>')[1].split('<link rel="stylesheet"')[0].replace('<title>Portfolio Tracker</title>', '<title>Portfolio Tracker Demo</title>');
  const body = html
    .split('<body>')[1]
    .split('<script src="app.js">')[0]
    .replace(
      '<main>',
      `<main>
    <div class="demo-bar">
      <p><b>Demo with simulated prices.</b> The holdings and alerts are examples, and nothing connects to a real market. Your changes are saved in this browser only. Move the market to trigger price alerts.</p>
      <div class="btns">
        <button class="btn small" id="demoUp" type="button">Market +3%</button>
        <button class="btn small" id="demoDown" type="button">Market −3%</button>
        <button class="btn small ghost" id="demoReset" type="button">Reset demo</button>
      </div>
    </div>`,
    );

  // Turn the ES modules into plain scripts that share one scope.
  const unmodule = (s) => s.replace(/^import .*$/gm, '').replace(/^export (class|function|const)/gm, '$1');
  const js = [
    unmodule(read('src/providers/mock.js')),
    unmodule(read('src/alerts.js')),
    read('demo/browser-backend.js'),
    read('public/app.js'),
    "document.getElementById('demoUp').onclick = () => demo.shock(3);",
    "document.getElementById('demoDown').onclick = () => demo.shock(-3);",
    "document.getElementById('demoReset').onclick = () => demo.reset();",
  ].join('\n');

  return `<!doctype html>
<!-- Generated by scripts/build-demo.mjs. Do not edit by hand; run "npm run build:demo". -->
<html lang="en">
<head>${head}<style>
${css}
</style>
</head>
<body>${body}<script>
${js}
</script>
</body>
</html>
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(OUT, buildDemo());
  console.log(`Wrote ${path.relative(root, OUT)}`);
}
